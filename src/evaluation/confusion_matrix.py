"""
confusion_matrix.py
===================
Phase 4 — Confusion Matrix Generator

Reads the `raw_predictions.npz` generated by `evaluate.py` and creates
visualizations of the confusion matrix. Since there are 383 classes, 
a full matrix is very dense, so this script generates:
1. High-resolution full confusion matrix (requires zooming in)
2. "Top Confused Classes" matrix highlighting the most common errors

Usage:
    python src/evaluation/confusion_matrix.py --exp_id 1
"""

import argparse
import logging
import os
import sys
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import seaborn as sns
from sklearn.metrics import confusion_matrix
import yaml

# ── Environment Setup ─────────────────────────────────────────────────────────
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
os.environ["PYTHONIOENCODING"] = "utf-8"

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(message)s",
    datefmt="%H:%M:%S",
    handlers=[logging.StreamHandler(sys.stdout)],
)
logger = logging.getLogger(__name__)


def load_config(path: str = "config.yaml") -> dict:
    with open(path, "r", encoding="utf-8") as f:
        return yaml.safe_load(f)


def load_class_names() -> dict:
    """Loads class names from sinhala_word_map.csv."""
    df = pd.read_csv("data/splits/sinhala_word_map.csv")
    # Returns mapping: {0: 'word1', 1: 'word2', ...}
    return dict(zip(df["class_id"], df["sinhala_word"]))


def generate_confusion_matrices(exp_id: int, top_k: int = 30) -> None:
    config = load_config("config.yaml")
    exp_config = config["experiments"][exp_id]
    
    results_dir = Path("results") / f"experiment_{exp_id}"
    preds_path = results_dir / "raw_predictions.npz"
    figures_dir = Path("results") / "figures"
    figures_dir.mkdir(parents=True, exist_ok=True)
    
    if not preds_path.exists():
        logger.error(f"Predictions not found at {preds_path}. Run evaluate.py first.")
        sys.exit(1)

    logger.info(f"Loading predictions from {preds_path}...")
    data = np.load(preds_path)
    y_true = data["y_true"]
    y_pred = data["y_pred"]
    
    class_map = load_class_names()
    num_classes = config["model"]["num_classes"]
    
    # Calculate full confusion matrix
    logger.info("Computing full confusion matrix...")
    cm = confusion_matrix(y_true, y_pred, labels=np.arange(num_classes))
    
    # Normalize by row (true class)
    cm_normalized = cm.astype('float') / cm.sum(axis=1)[:, np.newaxis]
    cm_normalized = np.nan_to_num(cm_normalized) # Replace NaNs with 0
    
    # ── 1. Full Confusion Matrix (High Res) ───────────────────────────────────
    logger.info("Plotting full high-resolution confusion matrix...")
    plt.figure(figsize=(40, 40))
    sns.heatmap(cm_normalized, cmap="Blues", cbar=False, xticklabels=False, yticklabels=False)
    plt.title(f"Full Normalized Confusion Matrix - EXP{exp_id} ({exp_config['name']})", fontsize=30)
    plt.xlabel("Predicted Class", fontsize=24)
    plt.ylabel("True Class", fontsize=24)
    
    full_cm_path = figures_dir / f"exp{exp_id}_full_confusion_matrix.png"
    plt.savefig(full_cm_path, dpi=150, bbox_inches="tight")
    plt.close()
    logger.info(f"Saved full matrix -> {full_cm_path}")
    
    # ── 2. Top-K Most Confused Classes ────────────────────────────────────────
    logger.info(f"Extracting top {top_k} most confused classes...")
    
    # Find classes with highest off-diagonal errors
    errors_per_class = []
    for i in range(num_classes):
        total_errors = np.sum(cm[i]) - cm[i, i]
        errors_per_class.append((i, total_errors))
        
    # Sort by error count descending
    errors_per_class.sort(key=lambda x: x[1], reverse=True)
    top_error_classes = [class_id for class_id, _ in errors_per_class[:top_k]]
    
    if len(top_error_classes) == 0 or all(cm[c].sum() == 0 for c in top_error_classes):
        logger.info("No errors found or too little data to plot top confused classes.")
        return

    # Extract sub-matrix
    sub_cm = cm[np.ix_(top_error_classes, top_error_classes)]
    
    # Normalize sub-matrix
    sub_cm_norm = sub_cm.astype('float') / sub_cm.sum(axis=1)[:, np.newaxis]
    sub_cm_norm = np.nan_to_num(sub_cm_norm)

    labels = [class_map.get(c, str(c)) for c in top_error_classes]

    plt.figure(figsize=(16, 14))
    sns.heatmap(
        sub_cm_norm, 
        annot=True, 
        fmt=".2f", 
        cmap="Reds", 
        xticklabels=labels, 
        yticklabels=labels
    )
    plt.title(f"Top {top_k} Confused Classes - EXP{exp_id} ({exp_config['name']})", fontsize=16)
    plt.xlabel("Predicted Class")
    plt.ylabel("True Class")
    plt.xticks(rotation=90)
    plt.yticks(rotation=0)
    
    top_cm_path = figures_dir / f"exp{exp_id}_top{top_k}_confusions.png"
    plt.savefig(top_cm_path, dpi=120, bbox_inches="tight")
    plt.close()
    logger.info(f"Saved top {top_k} matrix -> {top_cm_path}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Generate confusion matrices")
    parser.add_argument("--exp_id", type=int, required=True, choices=[1, 2, 3, 4, 5])
    parser.add_argument("--top_k", type=int, default=30, help="Number of worst classes to highlight")
    args = parser.parse_args()

    generate_confusion_matrices(args.exp_id, args.top_k)
